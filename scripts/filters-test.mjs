// 필터 교차 적용·비동기 응답·탭/브라우저 재방문 회귀 검사. 빌드 후 실행.
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { ROOT, serve, launch, stubNetwork, watch, waitForShell } from './lib/ui-harness.mjs';
const { base, close } = await serve();
const browser = await launch();
const errors = [];
let passed = 0;
function check(label, condition) { assert.ok(condition, label); console.log('PASS', label); passed++; }
const params = p => new URLSearchParams(new URL(p.url()).hash.split('?')[1] || '');
const ids = p => p.locator('.sheet .rows a.row[data-id]').evaluateAll(ns => [...new Set(ns.map(n => n.dataset.id))].sort());
const ready = async p => {
  await waitForShell(p, { markers: false });
  await p.waitForFunction(()=>['명산','걷기길'].includes(document.querySelector('.sheet .sheet-title')?.textContent));
};
try {
  const ctx = await browser.newContext({ viewport: { width: 390, height: 844 } });
  await stubNetwork(ctx);
  const page = watch(await ctx.newPage(), errors);
  const { mountains } = await (await page.request.get(base + '/data/mountains.json')).json();
  await page.goto(base + '/#/map?region=강원,충청&list=sanlim,bac&easy=1&hours=4&distance=10');
  await ready(page);
  const expected = mountains.filter(m => ['강원','충청'].includes(m.region) && (m.lists.sanlim || m.lists.bac) && m.trails.some(t => ['쉬움','보통'].includes(t.difficulty) && t.round_trip_hours > 0 && t.round_trip_hours <= 4 && t.distance_km > 0 && t.distance_km <= 10)).map(m=>m.id).sort();
  check('복수 권역·선정목록 OR, 코스·시간·거리 AND가 같은 코스에 적용', JSON.stringify(await ids(page)) === JSON.stringify(expected) && expected.length > 0);
  await page.getByRole('button', { name: /^필터/ }).click();
  const dlg = page.locator('dialog[open]');
  await dlg.getByRole('button', { name: '4개 목록 모두', exact: true }).click();
  check('4개 공통 선택 시 개별 목록과 중복 조건 제거', params(page).get('all') === '4' && !params(page).has('list') && await dlg.getByRole('button', { name:'BAC', exact:true }).getAttribute('aria-pressed') === 'false');
  await dlg.getByRole('button', { name: 'BAC', exact: true }).click();
  check('개별 목록을 선택하면 공통 조건 해제', !params(page).has('all') && params(page).get('list') === 'bac');
  await dlg.locator('.modal-foot .primary').click();
  const savedHash = new URL(page.url()).hash;
  await page.locator('.sheet-grabber').focus();
  await page.locator('.sheet-grabber').press('ArrowUp');
  await page.locator('.sheet-grabber').press('ArrowUp');
  await page.locator('.sheet .row[data-id]').first().click();
  await page.waitForSelector('.mt-title');
  await page.reload(); await page.waitForSelector('.mt-title');
  await page.setViewportSize({width:1440,height:1000});
  await page.locator('.tb-brand').click(); await ready(page);
  await page.setViewportSize({width:390,height:844});
  check('상세 새로고침·제목 링크 후 모든 목록 조건 보존', new URL(page.url()).hash === savedHash);
  await page.locator('.sheet-grabber').focus();
  await page.locator('.sheet-grabber').press('ArrowDown');
  await page.getByRole('button', { name:'걷기길', exact:true }).click();
  await page.getByRole('button', { name:'숲길', exact:true }).click();
  await page.getByRole('button', { name:'명산', exact:true }).click();
  await page.getByRole('button', { name:'걷기길', exact:true }).click();
  check('명산↔걷기길 전환 후 종류와 명산 필터 보존', params(page).get('walkkind') === 'forest' && params(page).get('region') === '강원,충청');
  await page.locator('.tb-input').fill('설악');
  await page.locator('.tb-input').press('Enter');
  await page.waitForFunction(() => document.querySelector('.shell')?.dataset.mode === 'mountain');
  check('걷기길 검색 제출 후 명산 컨트롤러·지도·필터 동기화', !params(page).has('mode') && !(await page.locator('.shell').evaluate(n=>n.classList.contains('dim-mountains'))) && params(page).get('q') === '설악');
  // 실제 브라우저 종료/재시작에 해당하는 localStorage만 새 컨텍스트로 옮긴다(sessionStorage 제외).
  await page.evaluate(() => { localStorage.setItem('kr100:theme','dark'); localStorage.setItem('kr100:prefs',JSON.stringify({v:1,courseCatalog:true,compareRoutes:true})); localStorage.setItem('kr100:maptype','terrain'); });
  const lastHash = new URL(page.url()).hash;
  await page.evaluate(()=>window.dispatchEvent(new Event('pagehide')));
  const savedView=await page.evaluate(()=>JSON.parse(localStorage.getItem('kr100:list-view')));
  const storage = await ctx.storageState(); await ctx.close();
  const fresh = await browser.newContext({ storageState:storage, viewport:{width:1440,height:1000} });
  await stubNetwork(fresh);
  const revisit = watch(await fresh.newPage(), errors);
  await revisit.goto(base + '/'); await ready(revisit);
  check('새 브라우저 방문 시 검색·권역·코스 조건 복원', new URL(revisit.url()).hash === lastHash);
  check('새 브라우저 방문 시 목록 높이와 지도 범위 저장 보존',!!savedView.viewport && await revisit.locator('.sheet').getAttribute('data-detent')===savedView.detent);
  check('테마·기능·지도 종류 설정 보존', await revisit.evaluate(()=>document.documentElement.dataset.theme==='dark' && JSON.parse(localStorage.getItem('kr100:prefs')).compareRoutes && localStorage.getItem('kr100:maptype')==='terrain'));
  await revisit.goto(base + '/#/map?region=제주'); await ready(revisit);
  check('명시적 URL은 저장된 조건보다 우선', (await ids(revisit)).every(id=>mountains.find(m=>m.id===id).region==='제주') && params(revisit).get('region') === '제주' && !params(revisit).has('q'));
  await revisit.getByRole('button', {name:'제주 조건 해제',exact:true}).click();
  await revisit.goto(base + '/'); await ready(revisit);
  check('마지막 조건 해제 후 재방문에도 이전 조건이 돌아오지 않음', params(revisit).size===0 && (await ids(revisit)).length===149);
  await revisit.goto(base + '/#/courses?region=강원&kind=official&q=코스');
  await revisit.waitForSelector('#crs-q');
  const coursesStorage=await fresh.storageState();
  const coursesCtx=await browser.newContext({storageState:coursesStorage}); await stubNetwork(coursesCtx);
  const courses=watch(await coursesCtx.newPage(),errors);
  await courses.goto(base+'/#/courses'); await courses.waitForSelector('#crs-q');
  check('코스 모음도 새 방문에서 검색·권역·종류 복원', await courses.locator('#crs-q').inputValue()==='코스' && await courses.locator('#crs-region').inputValue()==='강원' && await courses.locator('#crs-kind').inputValue()==='official');
  await coursesCtx.close();
  // 지도 위치 응답이 늦게 도착해도 해제한 가까운 순을 다시 켜지 않는다.
  const raceCtx = await browser.newContext(); await stubNetwork(raceCtx);
  await raceCtx.addInitScript(()=>{ navigator.geolocation.getCurrentPosition=success=>{window.deliverPosition=()=>success({coords:{latitude:37.5,longitude:127,accuracy:10}});}; });
  const race=watch(await raceCtx.newPage(),errors);
  await race.goto(base+'/#/map?'); await ready(race);
  await race.getByRole('button',{name:'가까운 순',exact:true}).click();
  await race.waitForFunction(()=>!!window.deliverPosition);
  await race.getByRole('button',{name:'가까운 순',exact:true}).click();
  await race.evaluate(()=>window.deliverPosition());
  check('늦은 위치 응답이 취소한 정렬을 복구하지 않음', !params(race).has('sort'));
  await raceCtx.close();
  // 걷기길 색인이 늦게 도착하는 동안 모달/목록의 개수가 함께 갱신된다.
  const delayedCtx=await browser.newContext(); await stubNetwork(delayedCtx);
  let release; const gate=new Promise(r=>release=r);
  await delayedCtx.route('**/data/trekking/index.json',async route=>{await gate; await route.continue();});
  const delayed=watch(await delayedCtx.newPage(),errors);
  await delayed.goto(base+'/#/map?'); await ready(delayed);
  await delayed.getByRole('button',{name:'필터',exact:true}).click();
  await delayed.getByRole('button',{name:'둘레길·걷기길 있는 산',exact:true}).click();
  check('색인 로딩 중 무관한 산을 결과로 표시하지 않음', (await ids(delayed)).length===0 && await delayed.locator('dialog .primary').textContent()==='걷기길 확인 중…');
  release();
  await delayed.waitForFunction(()=>/\d+곳 보기/.test(document.querySelector('dialog .primary')?.textContent));
  check('늦게 로드된 색인의 결과 수가 열린 모달과 일치', await delayed.locator('dialog .primary').textContent()===`${(await ids(delayed)).length}곳 보기`);
  await delayedCtx.close();
  const legacyCtx=await browser.newContext(); await stubNetwork(legacyCtx);
  await legacyCtx.addInitScript(()=>sessionStorage.setItem('kr100:last-list','#/map?region=제주'));
  const legacy=watch(await legacyCtx.newPage(),errors); await legacy.goto(base+'/'); await ready(legacy);
  check('기존 세션 저장 필터를 영구 저장소로 이전',params(legacy).get('region')==='제주' && await legacy.evaluate(()=>localStorage.getItem('kr100:last-list')?.includes('region=')));
  await legacyCtx.close();
  const blockedCtx=await browser.newContext({viewport:{width:1440,height:900}}); await stubNetwork(blockedCtx);
  await blockedCtx.addInitScript(()=>{Storage.prototype.getItem=()=>{throw new Error('blocked');};Storage.prototype.setItem=()=>{throw new Error('blocked');};});
  const blocked=watch(await blockedCtx.newPage(),errors); await blocked.goto(base+'/#/map?region=강원'); await ready(blocked);
  await blocked.locator('.sheet .row[data-id]').first().click(); await blocked.waitForSelector('.mt-title');
  await blocked.locator('.tb-brand').click(); await ready(blocked);
  check('저장소 사용 불가 때도 현재 탭의 필터·상세 복귀 정상',params(blocked).get('region')==='강원' && (await ids(blocked)).length>0);
  await blocked.goto(base+'/#/map?q='+encodeURIComponent('설악 비룡폭포')); await ready(blocked);
  check('공식 코스명과 여러 검색 단어가 명산 목록에도 연결',(await ids(blocked)).includes('seolaksan'));
  await blockedCtx.close();
  await revisit.goto(base+'/#/map?'); await ready(revisit);
  await mkdir(ROOT+'/shots/filters',{recursive:true});
  for(const width of [390,1440]) for(const theme of ['light','dark']) {
    await revisit.setViewportSize({width,height:900});
    await revisit.evaluate(t=>localStorage.setItem('kr100:theme',t),theme);
    await revisit.reload(); await ready(revisit);
    await revisit.getByRole('button',{name:'필터',exact:true}).click();
    await revisit.screenshot({path:`${ROOT}/shots/filters/${width}-${theme}.png`});
    check(`${width}px ${theme} 필터 모달 가로 넘침 없음`,await revisit.evaluate(()=>document.querySelector('dialog').getBoundingClientRect().right<=innerWidth));
    await revisit.locator('dialog .modal-close').click();
  }
  await fresh.close();
  check('브라우저 오류 없음',errors.length===0);
  console.log(`filters: ${passed} passed`);
} finally { await browser.close(); await close(); }
